"""
Eye Gaze Tracking Constants – TrueView AI

Defines landmark indices, gaze direction enums, iris position thresholds,
attention classification boundaries, and visualization color palettes.

Architecture Note:
    These constants are calibrated for the 68-point iBUG landmark scheme
    generated by Phase 7's LandmarkExtractor. When upgrading to MediaPipe
    468-point mesh, update the eye/iris landmark indices accordingly
    (MediaPipe iris: 468-472 left, 473-477 right).
"""

# ──────────────────────────────────────────────
# Eye Landmark Indices (iBUG 68-point convention)
# ──────────────────────────────────────────────
RIGHT_EYE_INDICES = list(range(36, 42))   # Points 36-41
LEFT_EYE_INDICES  = list(range(42, 48))   # Points 42-47

# Anchor landmark indices for quick reference
RIGHT_EYE_OUTER = 36
