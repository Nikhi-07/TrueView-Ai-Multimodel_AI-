LEFT_EYE_INNER  = 42
LEFT_EYE_OUTER  = 45

# ──────────────────────────────────────────────
# Gaze Direction Enums
# ──────────────────────────────────────────────
class GazeDirection:
    """Enumeration of gaze direction labels."""
    CENTER = "center"
    LEFT   = "left"
    RIGHT  = "right"
    UP     = "up"
    DOWN   = "down"

# ──────────────────────────────────────────────
# Attention Status Enums
# ──────────────────────────────────────────────
class AttentionStatus:
    """Enumeration of attention classification states."""
    FOCUSED      = "focused"
    DISTRACTED   = "distracted"
    LOOKING_AWAY = "looking_away"

# ──────────────────────────────────────────────
# Iris Position Thresholds (normalized 0.0 – 1.0)
#
# The eye bounding box is [0.0, 1.0] on both axes.
# Iris center position within this box determines
# gaze direction.
#
#  0.0 ───────── 0.35 ──── 0.65 ───────── 1.0
#  ◄── LEFT ──── │ CENTER │ ──── RIGHT ──►
#
# ──────────────────────────────────────────────
GAZE_HORIZONTAL_LEFT_THRESHOLD  = 0.35   # iris_x < this → looking LEFT
GAZE_HORIZONTAL_RIGHT_THRESHOLD = 0.65   # iris_x > this → looking RIGHT
GAZE_VERTICAL_UP_THRESHOLD      = 0.30   # iris_y < this → looking UP
GAZE_VERTICAL_DOWN_THRESHOLD    = 0.70   # iris_y > this → looking DOWN

# Confidence scaling factors
GAZE_CENTER_CONFIDENCE    = 0.95   # High confidence when centered
GAZE_DIRECTION_CONFIDENCE = 0.85   # Slightly lower for directional gazes
GAZE_EXTREME_CONFIDENCE   = 0.70   # Lower for extreme positions

# ──────────────────────────────────────────────
# Attention Analysis Parameters
# ──────────────────────────────────────────────
ATTENTION_WINDOW_SIZE     = 90     # Rolling window (frames) ≈ 3 sec @ 30 FPS
ATTENTION_FOCUSED_THRESHOLD   = 70.0   # Score ≥ 70% → FOCUSED
ATTENTION_DISTRACTED_THRESHOLD = 40.0  # Score 40-69% → DISTRACTED
                                        # Score < 40%  → LOOKING_AWAY

# Focus duration tracking
FOCUS_STREAK_RESET_FRAMES = 10    # Consecutive non-center frames to reset streak

